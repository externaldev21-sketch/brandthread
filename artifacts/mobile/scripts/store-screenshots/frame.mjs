#!/usr/bin/env node
/**
 * Wraps the raw iPhone captures from capture.mjs in App Store marketing
 * frames: a short headline over the real screen, black/white/silver only,
 * system font. The screen inside each frame is the unedited capture.
 *
 *   pnpm run screenshots -- --devices iphone-6.7in,iphone-6.1in
 *   pnpm run screenshots:frame
 *
 * Output: store-screenshots/framed/<device>/<NN-screen>.png at exactly the
 * pixel size App Store Connect asks for in that device's field.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { DEVICES, pixelSize } from './devices.mjs';
import { MOBILE_ROOT, launchBrowser } from './harness.mjs';

const RAW_DIR = path.join(MOBILE_ROOT, 'store-screenshots');
const OUT_DIR = path.join(RAW_DIR, 'framed');
const FRAMED_DEVICES = ['iphone-6.7in', 'iphone-6.1in'];

/**
 * Headline per screen id; screens without one are not framed. Only screens
 * that read black/white/silver and show real-looking content are framed.
 */
export const HEADLINES = {
  'buyer-feed': ['Shop the feed', 'Videos from the brands you follow'],
  'product-sheet': ['Tap to buy', 'Every item in the video, one tap away'],
  cart: ['One bag, every brand', 'Check out from many shops at once'],
  checkout: ['Fast, secure checkout', 'Express checkout and saved addresses'],
  'seller-dashboard': ['Run your brand', 'Sales, orders and payouts in one place'],
  'manufacturer-hub': ['Find a manufacturer', 'Samples and production, tracked'],
};

function html({ width, height, image, title, subtitle }) {
  // Proportions are relative to the canvas so 6.7" and 6.1" frames match.
  const pad = Math.round(width * 0.075);
  const screenW = Math.round(width * 0.8);
  const radius = Math.round(screenW * 0.11);
  return `<!doctype html><html><head><meta charset="utf-8"><style>
    html,body{margin:0;width:${width}px;height:${height}px;background:#0A0A0B;overflow:hidden}
    body{display:flex;flex-direction:column;align-items:center;
      font-family:-apple-system,BlinkMacSystemFont,"SF Pro Display","Helvetica Neue",Arial,sans-serif}
    h1{margin:${Math.round(height * 0.06)}px ${pad}px 0;color:#F7F7FA;font-weight:700;text-align:center;
      font-size:${Math.round(width * 0.075)}px;line-height:1.1;letter-spacing:-0.02em}
    p{margin:${Math.round(width * 0.025)}px ${pad}px 0;color:#A1A1AA;font-weight:500;text-align:center;
      font-size:${Math.round(width * 0.04)}px;line-height:1.3}
    .phone{margin-top:${Math.round(height * 0.045)}px;width:${screenW}px;border-radius:${radius}px;
      border:${Math.max(4, Math.round(width * 0.006))}px solid #3A3A3F;overflow:hidden;background:#000;
      box-shadow:0 0 0 ${Math.max(2, Math.round(width * 0.002))}px #8E8E93}
    .phone img{display:block;width:100%}
  </style></head><body>
    <h1>${title}</h1><p>${subtitle}</p>
    <div class="phone"><img src="data:image/png;base64,${image}"></div>
  </body></html>`;
}

async function main() {
  const browser = await launchBrowser();
  const written = [];
  try {
    for (const device of DEVICES.filter((d) => FRAMED_DEVICES.includes(d.id))) {
      const rawDir = path.join(RAW_DIR, device.id);
      if (!existsSync(rawDir)) {
        console.log(`– ${device.id}: no captures yet (run pnpm run screenshots -- --devices ${device.id})`);
        continue;
      }
      const { width, height } = pixelSize(device);
      const outDir = path.join(OUT_DIR, device.id);
      mkdirSync(outDir, { recursive: true });
      const page = await browser.newPage({ viewport: { width, height }, deviceScaleFactor: 1 });
      for (const name of readdirSync(rawDir).filter((n) => n.endsWith('.png')).sort()) {
        const id = name.replace(/^\d+-/, '').replace(/\.png$/, '');
        const headline = HEADLINES[id];
        if (!headline) continue;
        const image = readFileSync(path.join(rawDir, name)).toString('base64');
        await page.setContent(html({ width, height, image, title: headline[0], subtitle: headline[1] }));
        await page.waitForFunction(() => [...document.images].every((i) => i.complete));
        const file = path.join(outDir, name);
        await page.screenshot({ path: file });
        written.push(`| \`${device.id}/${name}\` | ${device.field} | ${width} × ${height} | ${headline[0]} |`);
        console.log(`✓ ${device.id} ${name}`);
      }
      await page.close();
    }
  } finally {
    await browser.close();
  }
  writeFileSync(
    path.join(OUT_DIR, 'README.md'),
    [
      '# Framed App Store screenshots',
      '',
      'Generated by `pnpm run screenshots:frame` from the raw captures one folder up. Upload these to',
      'App Store Connect → Previews and Screenshots. Do not edit by hand.',
      '',
      '| File | Upload to | Size (px) | Headline |',
      '| --- | --- | --- | --- |',
      ...written,
      '',
    ].join('\n'),
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
