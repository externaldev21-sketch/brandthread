#!/usr/bin/env node
/**
 * Bundles the legal drafts of record (content/legal/*.md) into
 * content/legal/generated.ts. React Native / Metro can't read .md at runtime,
 * so the app imports the generated module instead.
 *
 * [LAWYER REVIEW] lines are drafting notes for counsel. They are removed here,
 * so they are never shipped in the app bundle, let alone displayed.
 *
 *   node scripts/generate-legal-content.mjs           rewrite generated.ts
 *   node scripts/generate-legal-content.mjs --check   exit 1 if it is stale
 *
 * tests/legal-markdown.test.ts runs the same check, so a forgotten regenerate
 * fails CI.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = path.join(root, 'content', 'legal');
const outFile = path.join(sourceDir, 'generated.ts');

/** file name (without .md) → document id used by content/legal.ts */
export const LEGAL_MARKDOWN_FILES = {
  terms: 'terms',
  privacy: 'privacy',
  guidelines: 'community-guidelines',
  'seller-agreement': 'seller-agreement',
  'refund-policy': 'refund-policy',
};

const REVIEW_MARKER = '[LAWYER REVIEW]';

export function stripReviewMarkers(markdown) {
  return markdown
    .split(/\r?\n/)
    .filter((line) => !line.includes(REVIEW_MARKER))
    .join('\n')
    .replace(/\s*\[LAWYER REVIEW[^\]]*\]/g, '');
}

export function buildGeneratedModule() {
  const entries = Object.entries(LEGAL_MARKDOWN_FILES).map(([id, file]) => {
    const raw = fs.readFileSync(path.join(sourceDir, `${file}.md`), 'utf8');
    const text = stripReviewMarkers(raw).replace(/\n{3,}/g, '\n\n').trim() + '\n';
    return `  ${JSON.stringify(id)}: ${JSON.stringify(text)},`;
  });
  return [
    '// GENERATED by scripts/generate-legal-content.mjs from content/legal/*.md. Do not edit.',
    '// Run `pnpm --filter @workspace/mobile run legal:generate` after changing a .md draft.',
    '// Counsel review notes are removed before this file is written.',
    '',
    'export const LEGAL_MARKDOWN = {',
    ...entries,
    '} as const;',
    '',
    "export type LegalMarkdownId = keyof typeof LEGAL_MARKDOWN;",
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = buildGeneratedModule();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
    if (current !== next) {
      console.error('content/legal/generated.ts is out of date. Run: pnpm --filter @workspace/mobile run legal:generate');
      process.exit(1);
    }
    console.log('content/legal/generated.ts is up to date.');
  } else {
    fs.writeFileSync(outFile, next);
    console.log(`Wrote ${path.relative(root, outFile)}`);
  }
}
